// Generates the CloudFront Function that fronts the static export.
// The redirect map is inlined because CloudFront Functions cannot read files.
import fs from 'fs';
import path from 'path';

const root = path.join(path.dirname(new URL(import.meta.url).pathname), '..');
const redirects = JSON.parse(fs.readFileSync(path.join(root, 'out', 'redirects.json'), 'utf-8'));

const src = `// GENERATED by scripts/make-cf-function.mjs — do not edit by hand.
// Maps the WordPress URL shape onto Next's static export:
//   /a/b            -> /a/b.html      (URLs stay exactly as Google indexed them)
//   /a/b/           -> 301 /a/b       (one canonical form, no duplicate content)
//   retired pages   -> 301 destination
var REDIRECTS = ${JSON.stringify(redirects, null, 0)};

function handler(event) {
  var request = event.request;
  var uri = request.uri;

  var target = REDIRECTS[uri];
  if (target) {
    return {
      statusCode: 301,
      statusDescription: 'Moved Permanently',
      headers: { location: { value: target } }
    };
  }

  // Collapse trailing slashes onto the canonical slash-less URL.
  if (uri.length > 1 && uri.charAt(uri.length - 1) === '/') {
    var trimmed = uri.slice(0, -1);
    if (REDIRECTS[trimmed]) trimmed = REDIRECTS[trimmed];
    return {
      statusCode: 301,
      statusDescription: 'Moved Permanently',
      headers: { location: { value: trimmed } }
    };
  }

  if (uri === '/') {
    request.uri = '/index.html';
    return request;
  }

  // Extensionless paths are pages; everything else is a real asset.
  var lastSegment = uri.slice(uri.lastIndexOf('/') + 1);
  if (lastSegment.indexOf('.') === -1) {
    request.uri = uri + '.html';
  }
  return request;
}
`;

const outFile = path.join(root, 'scripts', 'cloudfront-function.js');
fs.writeFileSync(outFile, src);
console.log(`cloudfront function written (${Object.keys(redirects).length} redirects, ${(src.length / 1024).toFixed(1)} KB / 10 KB limit)`);
if (src.length > 10 * 1024) {
  console.error('EXCEEDS the 10 KB CloudFront Function size limit');
  process.exit(1);
}
